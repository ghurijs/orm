import type { Field } from '../../fields/base'
import { ForeignKey } from '../../fields/related'
import type { ConstraintSpec, ModelClass } from '../../models/types'
import { BaseSchemaEditor } from './base'

/**
 * PostgreSQL schema editor (also PGlite). Auto fields use identity columns; foreign keys are added as
 * deferred `ALTER TABLE … ADD CONSTRAINT … DEFERRABLE INITIALLY DEFERRED` statements once every table
 * exists.
 */
export class PostgresSchemaEditor extends BaseSchemaEditor {
  readonly dialect = 'postgresql' as const

  protected autoFieldSql(): string {
    return 'GENERATED BY DEFAULT AS IDENTITY'
  }

  protected inlineForeignKeySql(): string | null {
    return null
  }

  foreignKeySql(model: ModelClass, field: ForeignKey): string {
    const table = model._meta.dbTable
    const target = field.relatedModel
    const name = this.createName(table, [field.column], '_fk')
    return (
      `ALTER TABLE ${this.quoteName(table)} ADD CONSTRAINT ${this.quoteName(name)} FOREIGN KEY (${this.quoteName(field.column)}) ` +
      `REFERENCES ${this.quoteName(target._meta.dbTable)} (${this.quoteName(field.targetField.column)}) DEFERRABLE INITIALLY DEFERRED`
    )
  }

  protected override queueForeignKeys(model: ModelClass): void {
    for (const f of model._meta.concreteFields) {
      if (f instanceof ForeignKey && f.dbConstraint) this.deferredSql.push(this.foreignKeySql(model, f))
    }
  }

  createUniqueSql(model: ModelClass, u: { fields: string[]; name: string; condition?: string }): string {
    const cols = this.columnsFor(model, u.fields)
    if (u.condition) {
      return `CREATE UNIQUE INDEX ${this.quoteName(u.name)} ON ${this.quoteName(model._meta.dbTable)} (${cols.join(', ')}) WHERE ${u.condition}`
    }
    return `ALTER TABLE ${this.quoteName(model._meta.dbTable)} ADD CONSTRAINT ${this.quoteName(u.name)} UNIQUE (${cols.join(', ')})`
  }

  deleteUniqueSql(model: ModelClass, name: string): string {
    const c = model._meta.constraints.find((x) => x.name === name)
    if (c && c.type === 'unique' && c.condition) return `DROP INDEX ${this.quoteName(name)}`
    return `ALTER TABLE ${this.quoteName(model._meta.dbTable)} DROP CONSTRAINT ${this.quoteName(name)}`
  }

  protected async addCheckConstraint(
    model: ModelClass,
    c: Extract<ConstraintSpec, { type: 'check' }>,
  ): Promise<void> {
    await this.execute(
      `ALTER TABLE ${this.quoteName(model._meta.dbTable)} ADD CONSTRAINT ${this.quoteName(c.name)} CHECK (${c.check})`,
    )
  }

  protected async removeCheckConstraint(
    model: ModelClass,
    c: Extract<ConstraintSpec, { type: 'check' }>,
  ): Promise<void> {
    await this.execute(
      `ALTER TABLE ${this.quoteName(model._meta.dbTable)} DROP CONSTRAINT ${this.quoteName(c.name)}`,
    )
  }

  protected override deleteTableSql(table: string): string {
    return `DROP TABLE ${this.quoteName(table)} CASCADE`
  }

  async renameColumn(table: string, oldColumn: string, newColumn: string): Promise<void> {
    await this.execute(
      `ALTER TABLE ${this.quoteName(table)} RENAME COLUMN ${this.quoteName(oldColumn)} TO ${this.quoteName(newColumn)}`,
    )
  }

  async tableNames(): Promise<string[]> {
    const rows = await this.query(
      "SELECT table_name AS name FROM information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' ORDER BY table_name",
    )
    return rows.map((r) => String(r.name))
  }

  async columnNames(table: string): Promise<string[]> {
    const rows = await this.query(
      'SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = $1 ORDER BY ordinal_position',
      [table],
    )
    return rows.map((r) => String(r.name))
  }

  /** Reset identity sequences after inserting explicit ids (loaddata). */
  sequenceResetSql(model: ModelClass): string | null {
    const pk = model._meta.pk
    if (!pk?.isAutoField) return null
    const t = model._meta.dbTable
    return `SELECT setval(pg_get_serial_sequence('${this.quoteName(t)}', '${pk.column}'), COALESCE(MAX(${this.quoteName(pk.column)}), 1), MAX(${this.quoteName(pk.column)}) IS NOT NULL) FROM ${this.quoteName(t)}`
  }

  definitionFor(model: ModelClass, field: Field<any, any>): string | null {
    return this.columnSql(model, field)
  }
}
