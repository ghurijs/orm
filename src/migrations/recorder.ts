import type { Connection } from '../db/types'
import { quoteName } from '../query/sql'

export interface AppliedMigration {
  id: number
  app: string
  name: string
  applied: Date
}

/**
 * Records applied migrations in `ghuri_migrations(id, app, name, applied)` (Django's
 * `MigrationRecorder` / `django_migrations`).
 */
export class MigrationRecorder {
  static readonly TABLE = 'ghuri_migrations'
  private hasTableCache = false

  constructor(readonly connection: Connection) {}

  /** CREATE TABLE statement for the recorder table (IF NOT EXISTS). */
  static createTableSql(dialect: 'sqlite' | 'postgresql'): string {
    const t = quoteName(MigrationRecorder.TABLE)
    return dialect === 'postgresql'
      ? `CREATE TABLE IF NOT EXISTS ${t} ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "app" varchar(255) NOT NULL, "name" varchar(255) NOT NULL, "applied" timestamp with time zone NOT NULL)`
      : `CREATE TABLE IF NOT EXISTS ${t} ("id" integer NOT NULL PRIMARY KEY AUTOINCREMENT, "app" varchar(255) NOT NULL, "name" varchar(255) NOT NULL, "applied" text NOT NULL)`
  }

  async hasTable(): Promise<boolean> {
    if (this.hasTableCache) return true
    const sql =
      this.connection.dialect === 'postgresql'
        ? 'SELECT 1 AS x FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = $1'
        : "SELECT 1 AS x FROM sqlite_master WHERE type = 'table' AND name = ?"
    const res = await this.connection.execute(sql, [MigrationRecorder.TABLE])
    this.hasTableCache = res.rows.length > 0
    return this.hasTableCache
  }

  async ensureSchema(): Promise<void> {
    if (await this.hasTable()) return
    await this.connection.execute(MigrationRecorder.createTableSql(this.connection.dialect))
    this.hasTableCache = true
  }

  /** Applied migrations keyed by `app.name`. */
  async appliedMigrations(): Promise<Map<string, AppliedMigration>> {
    const out = new Map<string, AppliedMigration>()
    if (!(await this.hasTable())) return out
    const res = await this.connection.execute(
      `SELECT "id", "app", "name", "applied" FROM ${quoteName(MigrationRecorder.TABLE)} ORDER BY "id"`,
    )
    for (const r of res.rows) {
      const rec: AppliedMigration = {
        id: Number(r.id),
        app: String(r.app),
        name: String(r.name),
        applied: r.applied instanceof Date ? r.applied : new Date(String(r.applied)),
      }
      out.set(`${rec.app}.${rec.name}`, rec)
    }
    return out
  }

  /** INSERT statement recording `app.name` as applied (usable in a D1 batch). */
  appliedStatement(app: string, name: string): { sql: string; params: unknown[] } {
    const p = this.connection.dialect === 'postgresql' ? ['$1', '$2', '$3'] : ['?', '?', '?']
    return {
      sql: `INSERT INTO ${quoteName(MigrationRecorder.TABLE)} ("app", "name", "applied") VALUES (${p.join(', ')})`,
      params: [app, name, new Date().toISOString()],
    }
  }

  /** DELETE statement forgetting `app.name`. */
  unappliedStatement(app: string, name: string): { sql: string; params: unknown[] } {
    const p = this.connection.dialect === 'postgresql' ? ['$1', '$2'] : ['?', '?']
    return {
      sql: `DELETE FROM ${quoteName(MigrationRecorder.TABLE)} WHERE "app" = ${p[0]} AND "name" = ${p[1]}`,
      params: [app, name],
    }
  }

  async recordApplied(app: string, name: string): Promise<void> {
    await this.ensureSchema()
    const s = this.appliedStatement(app, name)
    await this.connection.execute(s.sql, s.params)
  }

  async recordUnapplied(app: string, name: string): Promise<void> {
    await this.ensureSchema()
    const s = this.unappliedStatement(app, name)
    await this.connection.execute(s.sql, s.params)
  }

  /** Forget every record (tests). */
  async flush(): Promise<void> {
    if (await this.hasTable())
      await this.connection.execute(`DELETE FROM ${quoteName(MigrationRecorder.TABLE)}`)
  }
}
